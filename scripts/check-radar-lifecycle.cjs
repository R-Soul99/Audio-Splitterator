// Run with Vite running: electron scripts/check-radar-lifecycle.cjs [URL]
const { app, BrowserWindow } = require('electron');
const assert = require('node:assert/strict');
// Real React lifecycle/handlers; inspect the acquisition latch to count ping events.
app.whenReady().then(async () => {
 const win = new BrowserWindow({show:false,width:1200,height:800,webPreferences:{backgroundThrottling:false,offscreen:true}});
 const run = async code => { try { return await win.webContents.executeJavaScript(code); } catch(e) { console.error(code); throw e; } };
 const wait = async code => { const end=Date.now()+15000; while(!await run(code)) { if(Date.now()>end) throw Error(code); await new Promise(r=>setTimeout(r,30)); } };
 try {
  if(process.argv[2]==='--production')await win.loadFile(require('node:path').join(__dirname,'../dist/index.html'));
  else await win.loadURL(process.argv[2] || 'http://localhost:3000/?standby=1');
  await run(`
   window.wave=()=>document.querySelector('[aria-label="Edit waveform"]');
   window.props=e=>e[Object.keys(e).find(k=>k.startsWith('__reactProps'))];
   window.component=()=>{ let root=wave()[Object.keys(wave()).find(k=>k.startsWith('__reactFiber'))];while(root.return)root=root.return;const queue=[root.stateNode.current];while(queue.length){const f=queue.shift();if(f.memoizedProps?.onAutoSplit && f.memoizedProps?.onSelectionChange)return f;if(f.child)queue.push(f.child);if(f.sibling)queue.push(f.sibling);} };
   window.importAudio=()=>{ const input=document.querySelector('input[type=file]'); const d=new DataTransfer();d.items.add(new File(['test'],'radar.wav'));input.files=d.files;input.dispatchEvent(new Event('change',{bubbles:true})); };
   window.FileReader=class { readAsArrayBuffer(){ this.result=new ArrayBuffer(8);this.onload(); } };
   window.AudioContext=class { currentTime=0;state='running';destination={};createBufferSource(){return {connect(){},start(){},stop(){},disconnect(){}};}resume(){return Promise.resolve();} decodeAudioData(){const b=new AudioBuffer({length:48000*20,numberOfChannels:2,sampleRate:48000});for(let c=0;c<2;c++){const a=b.getChannelData(c);a.fill(.1);a.fill(.001,48000*5,48000*7);for(const t of [5.6,5.8,6,6.2])a.fill(.1,Math.round(48000*t),Math.round(48000*(t+.02)));a.fill(.001,48000*12,48000*14);}return Promise.resolve(b);}close(){return Promise.resolve();} };
   window.move=t=>{const c=wave(),r=c.getBoundingClientRect();props(c).onPointerMove({clientX:r.left+t/20*r.width,clientY:r.top+r.height/2});};
   window.detect=()=>document.querySelector('[aria-label="Detect noise floor"]');
   window.splitter=()=>[...document.querySelectorAll('button')].find(b=>b.textContent.trim()==='Auto-Split');
   window.readout=()=>document.querySelector('[aria-label="Waveform readouts"]');
   window.floorOutput=()=>document.querySelector('[aria-label="Noise floor in dB"]');
   window.closeSplitter=()=>splitter();
   window.detectControls=()=>document.querySelectorAll('[aria-label="Detect noise floor"]');
   window.pings=0;window.radarTrace=[];void 0;
  `);
  await run('importAudio()');
  await wait('!!wave() && !document.querySelector("main").inert');
  await run(`let h=component().memoizedState;while(h){const v=h.memoizedState?.current;if(typeof v?.update==='function' && typeof v?.reset==='function'){const update=v.update.bind(v);v.update=t=>{const acquired=update(t);if(acquired)pings++;radarTrace.push({runStart:t?.runStart??null,zone:t?.zone??null,acquired});return acquired;};break;}h=h.next;} void 0;`);
  await run('move(5.5)');assert.equal(await run('pings'),0);
  await run('component().memoizedProps.onSelectionChange({start:5.2,end:5.4})');
  await wait('readout().textContent.includes("0:05")');
  await run('detect().click()');
  await wait('readout().textContent.includes("-57.0")');
  await run('move(5.5);move(6.5)');assert.equal(await run('pings'),1,'closed Splitter acquires once');
  await run('radarTrace=[];[5.5,5.7,5.9,6.1,6.5,6.1,5.9,5.7,5.5].forEach(move)');
  const trace=await run('radarTrace');
  console.log('Fragmented quiet-area waveform transitions:',JSON.stringify(trace));
  assert.equal(new Set(trace.map(row=>row.runStart)).size,1,'actual handler uses the shared Gap-filtered candidate');
  assert.equal(trace.filter(row=>row.acquired).length,0,'candidate switches retain existing acquisition');
  assert.equal(new Set(trace.map(row=>JSON.stringify(row.zone))).size,1,'all candidates share one envelope');
  assert.equal(await run('pings'),1,'fragmented area never repeats the ping');
  const before=await run('JSON.stringify(wave().getBoundingClientRect().toJSON())');
  await run('splitter().click()');await wait('splitter().getAttribute("aria-expanded")==="true"');
  assert.equal(await run('floorOutput().textContent'),'-57.0 dB');
  await run('move(6)');assert.equal(await run('pings'),1);
  await run('closeSplitter().click()');await wait('splitter().getAttribute("aria-expanded")==="false"');
  await run('move(6.2)');assert.equal(await run('pings'),1,'close preserves latch');
  assert.equal(await run('JSON.stringify(wave().getBoundingClientRect().toJSON())'),before,'stable waveform geometry');
  await run('move(9);move(6);move(12.5)');assert.equal(await run('pings'),3,'loss/reentry/distinct target');
  await run('importAudio()');await wait('!document.querySelector("main").inert && readout().textContent.includes("-45.0")');
  await run('move(6)');assert.equal(await run('pings'),3,'new recording requires detection');
  assert.equal(await run('detectControls().length'),1);
  await run('component().memoizedProps.onSelectionChange({start:12.2,end:13.8})');
  await wait('readout().textContent.includes("0:12")');
  await run('detect().click()');await wait('readout().textContent.includes("-57.0")');
  await run('move(12.5)');assert.equal(await run('pings'),4,'same target in new audio acquires afresh');
  // Real handlers: candidate rendering, hidden-preview snapping, sensitivity and Chop.
  await run(`
    window.candidateStrokes=[];window.orangePreviewStrokes=0;
    const nativeStroke=CanvasRenderingContext2D.prototype.stroke;
    CanvasRenderingContext2D.prototype.stroke=function(...args){
      if(this.canvas.getAttribute('aria-label')==='Waveform indicators' && this.strokeStyle.includes('165, 243, 252'))candidateStrokes.push(this.strokeStyle);
      if(this.canvas.getAttribute('aria-label')==='Waveform indicators' && this.strokeStyle==='#fbbf24' && this.getLineDash().join(',')==='4,4')orangePreviewStrokes++;
      return nativeStroke.apply(this,args);
    };
    window.preview=()=>document.querySelector('[aria-label="Show detected split preview"]');
    window.chop=()=>document.querySelector('[aria-label="Chop"]');
    window.sensitivity=value=>{const e=document.querySelector('[aria-label="Sensitivity"]');props(e).onKeyDown({key:value===0?'Home':'End',preventDefault(){}});};
    window.pointer=(type,t)=>{const c=wave(),r=c.getBoundingClientRect();props(c)[type]({type:type==='onPointerCancel'?'pointercancel':type,button:0,pointerId:1,clientX:r.left+t/20*r.width,clientY:r.top+r.height/2});};
    window.markers=()=>component().memoizedProps.markers;
    void 0;
  `);
  await run('move(13)');await wait('candidateStrokes.length>0');
  assert.equal(await run('detect().textContent.trim()'),'', 'Detect is ear-only');
  await run('preview().click()');await wait('preview().getAttribute("aria-pressed")==="false"');
  await run('candidateStrokes=[];move(13.2)');
  await new Promise(resolve=>setTimeout(resolve,100));
  assert.equal(await run('candidateStrokes.length'),0,'Preview Off suppresses candidate and radar trace drawing');
  await run('component().memoizedProps.onSelectionChange(null)');
  await new Promise(resolve=>setTimeout(resolve,30));
  await run('move(9)');await new Promise(resolve=>setTimeout(resolve,30));
  await run('pointer("onPointerDown",9)');await wait('!!component().memoizedState');
  await new Promise(resolve=>setTimeout(resolve,30));
  await run('pointer("onPointerUp",9)');
  assert.equal(await run('markers().length'),0,'normal single click does not split');
  await run(`(async()=>{
    const pause=()=>new Promise(resolve=>setTimeout(resolve,40));
    const selection=()=>component().memoizedProps.selection;
    const clear=async()=>{component().memoizedProps.onStop();component().memoizedProps.onSelectionChange(null);await pause();};
    const at=async(type,t,y=.5)=>{const c=wave(),r=c.getBoundingClientRect();props(c)[type]({type,button:0,pointerId:1,clientX:r.left+t/20*r.width,clientY:r.top+r.height*y});await pause();};
    const near=(actual,expected,message)=>{if(Math.abs(actual-expected)>1e-9)throw Error(message+': '+actual+' != '+expected);};
    for(const previewOn of [true,false]){
      preview().click();await pause();
      if(preview().getAttribute('aria-pressed')!==String(previewOn))throw Error('Wrong Preview state');
      await clear();await at('onPointerMove',11.9);await at('onPointerDown',11.9);await at('onPointerUp',11.9);
      near(component().memoizedProps.currentTime,11.9,'Normal click must ignore candidate at 13s');
      if(selection())throw Error('Normal click created a selection');
      await at('onPointerMove',12.25);await at('onPointerDown',12.25);await at('onPointerMove',13.75);
      near(selection().start,12.25,'Selection start must be raw');near(selection().end,13.75,'Live selection end must be raw');
      await at('onPointerUp',13.75);
      await at('onPointerMove',12.25);await at('onPointerDown',12.25);await at('onPointerMove',12.4);await at('onPointerUp',12.4);
      near(selection().start,12.4,'Left brace must be raw');
      await at('onPointerMove',13.75);await at('onPointerDown',13.75);await at('onPointerMove',13.6);await at('onPointerUp',13.6);
      near(selection().end,13.6,'Right brace must be raw');
      // Move the selection bar across the quiet run without changing its span.
      await at('onPointerMove',13,.03);await at('onPointerDown',13,.03);await at('onPointerMove',13.1,.03);await at('onPointerUp',13.1,.03);
      near(selection().start,12.5,'Selection move must be raw');near(selection().end,13.7,'Selection move preserves span');
      await clear();await at('onPointerMove',19.6);await at('onPointerDown',19.6);await at('onPointerMove',20.2);
      near(selection().end,20,'Live selection reaches exact end');await at('onPointerUp',20.2);near(selection().end,20,'Released selection reaches exact end');
      await clear();
    }
  })()`);
  assert.equal(await run('markers().length'),0,'normal editing never places a split');
  await run('chop().click()');await wait('chop().getAttribute("aria-pressed")==="true"');
  await run('move(9)');await new Promise(resolve=>setTimeout(resolve,30));
  await run('pointer("onPointerDown",9)');await new Promise(resolve=>setTimeout(resolve,30));
  await run('pointer("onPointerUp",9)');await wait('markers().length===1');
  assert.ok(Math.abs(await run('markers()[0].time')-9)<1e-9,'freehand Chop uses clicked position');
  await run('move(11.9)');await new Promise(resolve=>setTimeout(resolve,30));
  await run('pointer("onPointerDown",11.9)');await new Promise(resolve=>setTimeout(resolve,30));
  await run('pointer("onPointerUp",11.9)');await wait('markers().length===2');
  const snapped=await run('markers()[1].time');
  assert.ok(Math.abs(snapped - 13) < 1e-9, 'Chop snaps to the detected candidate at 13s when the quiet-run edge is within 150 ms, even with Preview Off');
  // Even with Chop On, moving an existing split is normal editing, not split placement.
  await run('move(13)');await new Promise(resolve=>setTimeout(resolve,30));
  await run('pointer("onPointerDown",13)');await new Promise(resolve=>setTimeout(resolve,30));
  await run('pointer("onPointerMove",13.2)');await new Promise(resolve=>setTimeout(resolve,30));
  await run('pointer("onPointerUp",13.2)');await new Promise(resolve=>setTimeout(resolve,30));
  assert.ok(Math.abs(await run('markers()[1].time')-13.2)<1e-9,'existing marker drag stays raw even with Chop On');
  assert.equal(await run('markers().length'),2,'marker drag never creates another split');
  await run('move(13.2)');await new Promise(resolve=>setTimeout(resolve,30));
  await run('pointer("onPointerDown",13.2)');await new Promise(resolve=>setTimeout(resolve,30));
  await run('pointer("onPointerMove",13)');await new Promise(resolve=>setTimeout(resolve,30));
  await run('pointer("onPointerUp",13)');await new Promise(resolve=>setTimeout(resolve,30));
  await run('sensitivity(0)');await wait(`document.querySelector('[aria-label="Sensitivity"]').getAttribute('aria-valuenow')==='0'`);
  await run('preview().click()');await wait('preview().getAttribute("aria-pressed")==="true"');
  await run('candidateStrokes=[];move(13)');await new Promise(resolve=>setTimeout(resolve,100));
  assert.equal(await run('candidateStrokes.length'),0,'low sensitivity removes marginal candidates');
  assert.ok((await run('readout().textContent')).includes('-57.0'),'detected floor reference is unchanged');
  await run('preview().click();sensitivity(100)');await wait('preview().getAttribute("aria-pressed")==="false"');
  await run('splitter().click()');await wait(`!!document.querySelector('[aria-label="Auto-split preview"]')`);
  await wait(`document.querySelector('[aria-label="Auto-split preview"]').getAttribute('aria-busy')==='false'`);
  assert.equal(await run(`document.querySelector('[aria-label="Auto-split preview"] strong').textContent`),'2','underlying Auto-Split predictions exist');
  await run('preview().click()');await wait('preview().getAttribute("aria-pressed")==="true"');
  await run('orangePreviewStrokes=0;candidateStrokes=[];move(13.2)');await wait('candidateStrokes.length>0');
  assert.equal(await run('orangePreviewStrokes'),0,'Preview On draws radar indicators without orange prediction lines');
  await run('preview().click()');await wait('preview().getAttribute("aria-pressed")==="false"');
  await run('[...document.querySelectorAll("button")].find(button=>button.textContent.trim()==="Apply").click()');
  await wait('markers().length>=3');
  assert.equal(await run('markers().filter(marker=>marker.id.startsWith("marker-auto-")).length'),1,'Auto-Split adds the other gap with Preview Off and preserves the existing Chop candidate');
  assert.equal(await run('markers().filter(marker=>Math.abs(marker.time-13)<1e-9).length'),1,'Auto-Split does not duplicate the manual Chop marker at the candidate');
  await run('preview().click()');await wait('preview().getAttribute("aria-pressed")==="true"');
  await run('candidateStrokes=[];move(13.1)');await wait('candidateStrokes.length>0');
  assert.equal(await run('detectControls().length'),1,'Preview restores current candidates without detection');
  await new Promise(resolve => setTimeout(resolve, 300));
  await win.webContents.capturePage().then(image=>require('fs').writeFileSync(require('path').join(app.getPath('temp'), 'splitterator-radar-review.png'),image.toPNG()));
  console.log('PASS: independent detection, panel toggles, acquisition pings, new audio reset, shared Splitter threshold, stable geometry, raw normal editing with Preview On/Off, Chop candidate snapping');app.exit(0);
 } catch(e){console.error(e);app.exit(1);}
});
